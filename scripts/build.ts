// Bundles everything the tutorial pages need into plain script files, so the
// pages work when opened straight from disk (file://) with no server:
//
//   tutorials/lib/jgz.js               the js-game-zero engine (script-tag build)
//   tutorials/lib/data/<game>.js       a game's images (as data URLs) and the
//                                      code for every tutorial step
//   tutorials/lib/data/games.js        the list of tutorials, from each game's
//                                      tutorial.json, for the hub and play.html
//
// Step code lives in tutorials/steps/<game>/NN-name.js. The finished game,
// games/<game>/main.js, is always added as the last step, "final", so the
// tutorial can never drift away from the real game.
//
// Usage: bun scripts/build.ts

import { existsSync } from "node:fs";
import {
  copyFile,
  mkdir,
  readdir,
  readFile,
  writeFile,
} from "node:fs/promises";
import { extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const engineSource = join(
  root,
  "../js-game-zero/packages/browser-runtime/dist/browser/browser.js",
);
const libDir = join(root, "tutorials/lib");

const MIME: Record<string, string> = {
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".wav": "audio/wav",
  ".ogg": "audio/ogg",
  ".mp3": "audio/mpeg",
  ".m4a": "audio/mp4",
  ".ttf": "font/ttf",
  ".otf": "font/otf",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
};

const ASSET_FOLDERS = ["images", "sounds", "music", "fonts"];

if (existsSync(engineSource)) {
  await copyFile(engineSource, join(libDir, "jgz.js"));
  console.log("engine  → tutorials/lib/jgz.js");
} else if (!existsSync(join(libDir, "jgz.js"))) {
  throw new Error(
    `No engine build found at ${engineSource}. Run \`bun run build\` in js-game-zero first.`,
  );
}

await mkdir(join(libDir, "data"), { recursive: true });

const listed: Record<string, unknown>[] = [];

for (const game of (await readdir(join(root, "games"))).sort()) {
  const gameDir = join(root, "games", game);
  if (!existsSync(join(gameDir, "main.js"))) continue;

  const assets: Record<string, string> = {};
  for (const folder of ASSET_FOLDERS) {
    const dir = join(gameDir, folder);
    if (!existsSync(dir)) continue;
    for (const file of (await readdir(dir)).sort()) {
      const type = MIME[extname(file).toLowerCase()];
      if (!type) continue;
      const bytes = await readFile(join(dir, file));
      assets[`${folder}/${file}`] =
        `data:${type};base64,${bytes.toString("base64")}`;
    }
  }

  const steps: Record<string, string> = {};
  const stepsDir = join(root, "tutorials/steps", game);
  if (existsSync(stepsDir)) {
    for (const file of (await readdir(stepsDir)).sort()) {
      if (extname(file) !== ".js") continue;
      steps[file.replace(/\.js$/, "")] = await readFile(
        join(stepsDir, file),
        "utf8",
      );
    }
  }
  steps.final = await readFile(join(gameDir, "main.js"), "utf8");

  const bundle = {
    assets,
    steps,
    order: Object.keys(steps),
  };
  const out = `// Generated by scripts/build.ts — do not edit by hand.\nJGZT.register(${JSON.stringify(game)}, ${JSON.stringify(bundle)});\n`;
  await writeFile(join(libDir, "data", `${game}.js`), out);
  console.log(
    `${game.padEnd(14)} → tutorials/lib/data/${game}.js (${Object.keys(assets).length} assets, ${bundle.order.length} steps)`,
  );

  // tutorial.json puts the game on the hub. Catch the easy mistakes here.
  const infoFile = join(gameDir, "tutorial.json");
  if (!existsSync(infoFile)) continue;
  const info = JSON.parse(await readFile(infoFile, "utf8"));
  for (const field of ["title", "page", "theme", "tagline", "help"]) {
    if (typeof info[field] !== "string" || !info[field])
      throw new Error(`games/${game}/tutorial.json needs a "${field}"`);
  }
  if (!existsSync(join(root, "tutorials", info.page)))
    console.warn(`  ⚠ tutorials/${info.page} doesn't exist yet`);
  for (const [path] of info.card?.sprites ?? []) {
    if (!assets[path])
      console.warn(`  ⚠ card sprite ${path} isn't in the game`);
  }
  listed.push({ id: game, ...info });
}

listed.sort((a, b) => Number(a.order ?? 999) - Number(b.order ?? 999));
await writeFile(
  join(libDir, "data", "games.js"),
  `// Generated by scripts/build.ts from games/*/tutorial.json — do not edit by hand.\nwindow.JGZT_GAMES = ${JSON.stringify(listed, null, 2)};\n`,
);
console.log(
  `hub     → tutorials/lib/data/games.js (${listed.length} tutorials)`,
);
